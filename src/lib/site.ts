export function url(path = "") {
  return `${import.meta.env.BASE_URL.replace(/\/$/, "")}/${path.replace(/^\//, "")}`;
}
export function localeUrl(lang: Lang, path = "") {
  return url(`${lang}/${path}`);
}
export function otherLang(lang: Lang): Lang {
  return lang === "zh" ? "en" : "zh";
}
